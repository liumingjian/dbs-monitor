package main

import (
	"bytes"
	"strings"
	"testing"

	"github.com/liumingjian/dbs-monitor/internal/metric"
)

func TestRenderAppendixIncludesEveryDeclaredMetricAndTask(t *testing.T) {
	var output bytes.Buffer
	if err := renderAppendix(&output); err != nil {
		t.Fatalf("render metric appendix: %v", err)
	}
	contents := output.String()

	if !strings.Contains(contents, "Code generated by go run ./cmd/metric-appendix; DO NOT EDIT.") {
		t.Fatal("generated-file marker is missing")
	}
	for _, declaration := range metric.Metrics {
		rowPrefix := "| `" + declaration.ID.String() + "` |"
		if count := strings.Count(contents, rowPrefix); count != 1 {
			t.Errorf("metric %s row count = %d, want 1", declaration.ID, count)
		}
	}
	for _, task := range metric.Tasks {
		heading := "### Task `" + string(task.ID) + "`"
		if !strings.Contains(contents, heading) {
			t.Errorf("task %s heading is missing", task.ID)
		}
		if !strings.Contains(contents, strings.TrimSpace(task.SQL)) {
			t.Errorf("task %s SQL is missing", task.ID)
		}
	}
}
